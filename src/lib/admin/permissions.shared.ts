export interface ClientPermissionFlags {
  canViewAppointments: boolean;
  canManageAppointments: boolean;
  canCreateManualBookings: boolean;
  canViewPatientDetails: boolean;
  canAddInternalNotes: boolean;
  canManageSchedules: boolean;
  canManageEnquiries: boolean;
  canRetryNotifications: boolean;
  canExportAppointments: boolean;
  canViewAuditLogs: boolean;
  canManageUsers: boolean;
  canManageRoles: boolean;
  canRevokeSessions: boolean;
  canViewCms: boolean;
  canCreateContent: boolean;
  canEditContent: boolean;
  canPublishContent: boolean;
  canArchiveContent: boolean;
  canDeleteDraftContent: boolean;
  canManageDoctorContent: boolean;
  canManageTestimonials: boolean;
  canManageMedia: boolean;
  canManageSiteSettings: boolean;
  canManageSeo: boolean;
  canPreviewContent: boolean;
}

export function computeClientPermissionFlags(permissions: AdminPermissionType[]): ClientPermissionFlags {
  const permSet = new Set(permissions);
  return {
    canViewAppointments: permSet.has(ADMIN_PERMISSIONS.VIEW_APPOINTMENTS),
    canManageAppointments: permSet.has(ADMIN_PERMISSIONS.MANAGE_APPOINTMENTS),
    canCreateManualBookings: permSet.has(ADMIN_PERMISSIONS.CREATE_MANUAL_BOOKINGS),
    canViewPatientDetails: permSet.has(ADMIN_PERMISSIONS.VIEW_PATIENT_DETAILS),
    canAddInternalNotes: permSet.has(ADMIN_PERMISSIONS.ADD_INTERNAL_NOTES),
    canManageSchedules: permSet.has(ADMIN_PERMISSIONS.MANAGE_SCHEDULES),
    canManageEnquiries: permSet.has(ADMIN_PERMISSIONS.MANAGE_ENQUIRIES),
    canRetryNotifications: permSet.has(ADMIN_PERMISSIONS.RETRY_NOTIFICATIONS),
    canExportAppointments: permSet.has(ADMIN_PERMISSIONS.EXPORT_APPOINTMENTS),
    canViewAuditLogs: permSet.has(ADMIN_PERMISSIONS.VIEW_AUDIT_LOGS),
    canManageUsers: permSet.has(ADMIN_PERMISSIONS.MANAGE_USERS),
    canManageRoles: permSet.has(ADMIN_PERMISSIONS.MANAGE_ROLES),
    canRevokeSessions: permSet.has(ADMIN_PERMISSIONS.REVOKE_SESSIONS),
    canViewCms: permSet.has(ADMIN_PERMISSIONS.VIEW_CMS),
    canCreateContent: permSet.has(ADMIN_PERMISSIONS.CREATE_CONTENT),
    canEditContent: permSet.has(ADMIN_PERMISSIONS.EDIT_CONTENT),
    canPublishContent: permSet.has(ADMIN_PERMISSIONS.PUBLISH_CONTENT),
    canArchiveContent: permSet.has(ADMIN_PERMISSIONS.ARCHIVE_CONTENT),
    canDeleteDraftContent: permSet.has(ADMIN_PERMISSIONS.DELETE_DRAFT_CONTENT),
    canManageDoctorContent: permSet.has(ADMIN_PERMISSIONS.MANAGE_DOCTOR_CONTENT),
    canManageTestimonials: permSet.has(ADMIN_PERMISSIONS.MANAGE_TESTIMONIALS),
    canManageMedia: permSet.has(ADMIN_PERMISSIONS.MANAGE_MEDIA),
    canManageSiteSettings: permSet.has(ADMIN_PERMISSIONS.MANAGE_SITE_SETTINGS),
    canManageSeo: permSet.has(ADMIN_PERMISSIONS.MANAGE_SEO),
    canPreviewContent: permSet.has(ADMIN_PERMISSIONS.PREVIEW_CONTENT),
  };
}
